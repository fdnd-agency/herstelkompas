        <h2>Waarom surftherapie werkt</h2>
        <section>
            <img src="#" alt=""> <!-- add img later -->
            <h3>Blue Mind Theory</h3>
            <p>Volgens marien bioloog Wallace J. Nichols heeft verblijf in of bij blauw water een diepgaand therapeutisch effect:</p>
            <ul>
                <li><strong>Verlaging van cortisol</strong> – minder stress, beter herstel</li>
                <li><strong>Verhoging van serotonine</strong> – meer geluksgevoel</li>
                <li><strong>Verbondenheid met de aarde</strong> – meer creativiteit, minder angst</li>
                <li><strong>Beter herstel van de hersenen </strong> – essentieel voor onze deelnemers</li>
            </ul>
            <p><em>"Dit is belangrijk om te kunnen herstellen van een fysieke inspanning en om belastbaarheid op te bouwen."</em></p>
        </section>
        <section>
            <img src="#" alt=""> <!-- add img later -->
            <h3>De Flow State</h3>
            <p>Door het programma van Zelfzorg aan Zee komen de deelnemers weer in een flow state. Surfen vergt aandacht: Het in evenwicht houden van het surfboard (en jezelf) zorgt voor het omgaan met de golven in de zee en het luisteren naar de surfinstructies.</p>
            <p>Door deze activiteiten heb je weinig ruimte om aan andere dingen te denken. Dit wordt de flow state genoemd: Helemaal in het moment leven.</p>
            <p>De flow state heeft een verlagend effect op stress, angst en depressie.</p>
        </section>
        <img src="/img/deelnemeren.svg" alt="deelnemeren">
        <section>
            <img src="#" alt=""> <!-- add img later -->
            <h3>Wat is surftherapie?</h3>
            <p>Surftherapie kan worden gedefinieerd als een fysieke activiteitinterventie waarbij surfen wordt gebruikt als middel om positieve verandering te bereiken, waaronder een verbetering van de mentale gezondheid.</p>
            <p>Volgens de Blue Mind Theory heeft water een therapeutische werking, daarnaast is lichamelijk actief zijn ook een belangrijk onderdeel van dit programma. Actief zijn en het leren van iets nieuws, activeren stofjes in je hersenen. Waaronder dopamine, oxytocine, serotonine en endorfine.</p>
            <p>Deze stofjes bevorderen concentratie en verminderen stress, vermoeidheid, pijn, angst- en depressieklachten.</p>
        </section>
